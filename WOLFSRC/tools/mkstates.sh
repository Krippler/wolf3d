#!/bin/sh
#
# mkstates.sh CC CFLAGS... > states.c
#
# Every actor state the build defines, in a table: a savegame stores an
# actor's state as its place in this table instead of as a pointer, which
# would mean nothing to the next build of the engine.
#
# The sources are run through the preprocessor first, with the build's own
# defines, so the states inside #ifdef SPEAR and the like are listed exactly
# when they are compiled. Sorted by name, so the order -- and with it every
# savegame -- does not change when the code around them does.
#
cc="$1"
shift

names=$(cat WL_*.C | "$cc" -E -P "$@" -x c - 2>/dev/null \
	| grep -o '^[[:space:]]*statetype[[:space:]][[:space:]]*s_[A-Za-z0-9_]*' \
	| sed 's/.*statetype[[:space:]]*//' | sort -u)

echo "// Generated by tools/mkstates.sh. Do not edit."
echo
echo "typedef struct statestruct statetype;"
echo
for n in $names; do
	echo "extern statetype $n;"
done
echo
echo "statetype *allstates[] ="
echo "{"
for n in $names; do
	echo "	&$n,"
done
echo "};"
echo
echo "int numstates = sizeof(allstates)/sizeof(allstates[0]);"
